"""Write docs/api_examples.md: one real (masked) example response per endpoint.

Examples come from the live API over the processed data, so they always reflect
the current response shapes. Lists are cut to their first item.

Usage (from backend/, after the pipeline has run):  python scripts/export_api_examples.py
"""
from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
warnings.filterwarnings("ignore")

from fastapi.testclient import TestClient  # noqa: E402

from app.main import app  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "docs" / "api_examples.md"


def trim(x, depth=0):
    if isinstance(x, list):
        return [trim(v, depth + 1) for v in x[:1]] + (["…"] if len(x) > 1 else [])
    if isinstance(x, dict):
        items = list(x.items())
        keep = items if depth < 1 or len(items) <= 12 else items[:8]
        d = {k: trim(v, depth + 1) for k, v in keep}
        if len(keep) < len(items):
            d["…"] = f"{len(items) - len(keep)} more keys"
        return d
    if isinstance(x, float):
        return round(x, 3)
    return x


def main() -> None:
    c = TestClient(app)
    account = c.get("/api/leads").json()[0]["account_id"]
    ring = c.get("/api/graph/rings").json()[-1]["ring_id"]
    complaint = c.get("/api/complaints").json()[0]["complaint_id"]
    endpoints = [
        ("GET /api/health", "/api/health"),
        ("GET /api/stats", "/api/stats"),
        ("GET /api/leads", "/api/leads?limit=3"),
        ("GET /api/alerts", "/api/alerts"),
        ("GET /api/accounts", "/api/accounts?tier=HIGH"),
        ("GET /api/accounts/{id}", f"/api/accounts/{account}"),
        ("GET /api/accounts/{id}/timeline", f"/api/accounts/{account}/timeline?limit=2"),
        ("GET /api/accounts/{id}/trail", f"/api/accounts/{account}/trail?hops=2&max_paths=2"),
        ("GET /api/graph/rings", "/api/graph/rings"),
        ("GET /api/graph/rings/{ring_id}", f"/api/graph/rings/{ring}"),
        ("GET /api/complaints", "/api/complaints"),
        ("GET /api/complaints/{id}/matches", f"/api/complaints/{complaint}/matches"),
        ("GET /api/models/summary", "/api/models/summary"),
    ]
    out = ["# API examples", "",
           "Generated by `backend/scripts/export_api_examples.py` from the live API (identifiers masked).",
           "Lists are cut to the first item (`\"…\"` marks more). Field definitions: `docs/openapi.json`.", ""]
    for title, url in endpoints:
        body = c.get(url).json()
        if url == "/api/models/summary":
            card, ev = body["model_card"], body["evaluation"] or {}
            body = {
                "model_card": {k: card[k] for k in ("generated_at", "phase", "labels_available", "training_data", "score_weights")}
                | {"versions": "…", "models": "… isolation_forest, shap_tree_explainer, hdbscan_window_roles, hdbscan_account_roles"},
                "evaluation": {"note": ev.get("note"), "contamination": ev.get("contamination"),
                               "injection": {"roc_auc": ev.get("injection", {}).get("roc_auc"), "…": "pr_auc, precision_at_k, recall_at_threshold, recall_by_pattern, runs"},
                               "…": "contamination_sweep, stability, agreement_with_rules, clustering, top10, model_card"},
                "role_profiles": trim(body["role_profiles"], 1), "account_roles": trim(body["account_roles"], 1),
            }
        else:
            body = trim(body)
        out += [f"## `{title}`", "", f"`{url}`", "", "```json", json.dumps(body, indent=2, ensure_ascii=False), "```", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
